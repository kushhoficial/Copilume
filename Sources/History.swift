import Foundation

struct StoredImage: Codable, Equatable {
    let png: Data
    let width: Int
    let height: Int
    var isWithinLimits: Bool {
        width > 0 && height > 0 && width <= 8192 && height <= 8192 &&
        width * height <= 16_000_000 && !png.isEmpty && png.count <= 8_000_000
    }
}

struct Clip: Codable, Equatable {
    let id: UUID
    let text: String
    let date: Date
    var image: StoredImage? = nil
    var isImage: Bool { image != nil }
    var byteCount: Int { text.utf8.count + (image?.png.count ?? 0) }
    var displayText: String { image.map { "Imagem • \($0.width) × \($0.height)" } ?? text }
    var pinned: Bool? = false
    var isPinned: Bool { pinned == true }
    var isLink: Bool { guard !isImage else { return false }; let value = text.trimmingCharacters(in: .whitespacesAndNewlines).lowercased(); return value.hasPrefix("https://") || value.hasPrefix("http://") }
    var singleLine: String { text.split(whereSeparator: { $0.isWhitespace }).joined(separator: " ") }
    init(_ text: String) { id = UUID(); self.text = text; date = Date() }
    init(image: StoredImage) { id = UUID(); text = ""; date = Date(); self.image = image }
}

final class History {
    static let excludedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "com.agilebits.onepassword.password", "de.petermaurer.TransientPasteboardType"
    ]
    private(set) var items: [Clip] = []
    var limit: Int { didSet { limit = max(1, min(5000, limit)); trim() } }
    var paused = false
    var persistent = false
    let file: URL
    init(limit: Int = 200, file: URL) { self.limit = max(1, min(5000, limit)); self.file = file }
    @discardableResult func capture(_ text: String?, types: Set<String>) -> Bool {
        guard !paused, types.isDisjoint(with: Self.excludedTypes), let text,
              !text.isEmpty, text.utf8.count <= 2_000_000, !(items.first.map { !$0.isImage && $0.text == text } ?? false) else { return false }
        let clip = Clip(text); items.insert(clip, at: 0); trim(); return items.contains { $0.id == clip.id }
    }
    @discardableResult func captureImage(_ image: StoredImage, types: Set<String>) -> Bool {
        guard !paused, types.isDisjoint(with: Self.excludedTypes), image.isWithinLimits,
              items.first?.image != image else { return false }
        let clip = Clip(image: image); items.insert(clip, at: 0); trim()
        return items.contains { $0.id == clip.id }
    }
    func trim() {
        var total = items.reduce(0) { $0 + $1.byteCount }
        while items.count > limit || total > 24_000_000 {
            // Protect pins while capacity allows. The hard limits always apply.
            let index = items.lastIndex(where: { !$0.isPinned }) ?? (items.count - 1)
            total -= items[index].byteCount; items.remove(at: index)
        }
    }
    func togglePin(_ id: UUID) { if let index = items.firstIndex(where: { $0.id == id }) { items[index].pinned = !items[index].isPinned } }
    func clearUnpinned() { items.removeAll { !$0.isPinned } }
    func remove(_ id: UUID) { items.removeAll { $0.id == id } }
    func clear() { items.removeAll() }
    func search(_ query: String, scope: Int = 0) -> [Clip] {
        items.filter {
            (query.isEmpty || $0.displayText.range(of: query, options: [.caseInsensitive, .diacriticInsensitive]) != nil) &&
            (scope == 0 || (scope == 1 && $0.isPinned) || (scope == 2 && $0.isLink) || (scope == 3 && !$0.isLink && !$0.isImage) || (scope == 4 && $0.isImage))
        }
    }
    func save() throws {
        guard persistent else { return }
        let directory = file.deletingLastPathComponent()
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: directory.path)
        let data = try JSONEncoder().encode(items)
        guard data.count <= 50_000_000 else { throw CocoaError(.fileWriteOutOfSpace) }
        try data.write(to: file, options: .atomic)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
    }
    func load() throws {
        guard persistent, FileManager.default.fileExists(atPath: file.path) else { return }
        let size = try file.resourceValues(forKeys: [.fileSizeKey]).fileSize ?? 0
        guard size <= 50_000_000 else { throw CocoaError(.fileReadTooLarge) }
        let data = try Data(contentsOf: file)
        guard data.count <= 50_000_000 else { throw CocoaError(.fileReadTooLarge) }
        let decoded = try JSONDecoder().decode([Clip].self, from: data)
        items = decoded.filter { clip in
            if let image = clip.image { return image.isWithinLimits && clip.text.isEmpty }
            return !clip.text.isEmpty && clip.text.utf8.count <= 2_000_000
        }; trim()
    }
    func deleteSaved() throws {
        if FileManager.default.fileExists(atPath: file.path) { try FileManager.default.removeItem(at: file) }
    }
}
